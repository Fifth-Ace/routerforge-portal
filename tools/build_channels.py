#!/usr/bin/env python3
"""Single-source deterministic multi-browser release builder. No network, npm downloads or secrets."""
import hashlib, json, pathlib, re, subprocess, sys, zipfile
R=pathlib.Path(__file__).resolve().parent.parent
M=json.loads((R/'manifest.json').read_text(encoding='utf-8'))
V=M['version']
if not re.fullmatch(r'\d+\.\d+\.\d+(?:\.\d+)?',V): raise SystemExit('BAD_VERSION')
# Derive ALL clients from exactly the same source tree.
for tool in ['package_release.py','build_userscript.py']:
    subprocess.run([sys.executable,str(R/'tools'/tool)],check=True)
D=R/'release';D.mkdir(exist_ok=True)
N=R/'dist'/f'routerforge-portal-v{V}-install.zip'
if not N.exists(): raise SystemExit('MISSING_NATIVE_PACKAGE')
chromium=D/f'routerforge-portal-chromium-v{V}.zip'
chromium.write_bytes(N.read_bytes())
with zipfile.ZipFile(N) as z:
    files={n:z.read(n) for n in z.namelist()}
firefox=dict(M)
firefox['background']={'scripts':['background.js']}
firefox['browser_specific_settings']={'gecko':{'id':'routerforge-portal@fifth-ace.github.io','strict_min_version':'121.0'}}
files['manifest.json']=(json.dumps(firefox,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode('utf-8')
firefox_file=D/f'routerforge-portal-firefox-UNSIGNED-DEV-v{V}.xpi'
with zipfile.ZipFile(firefox_file,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
    for name in sorted(files):
        info=zipfile.ZipInfo(name,date_time=(2026,1,1,0,0,0))
        info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=(0o644<<16)
        z.writestr(info,files[name],compress_type=zipfile.ZIP_DEFLATED,compresslevel=9)
channels={
  'version':V,'repository':'Fifth-Ace/routerforge-portal','publication':'GH release asset generated by tag workflow',
  'chrome':'Chromium ZIP or userscript',
  'edge':'Chromium ZIP or userscript',
  'opera':'Chromium ZIP or userscript',
  'firefox':'Userscript recommended; unsigned XPI temporary testing only',
  'release_policy':'No browser-store publication; no silent native extension auto-update',
  'userscript_updates':'GitHub releases/latest/download after FIRST official release',
}
(D/'CHANNELS.json').write_text(json.dumps(channels,ensure_ascii=False,indent=2,sort_keys=True)+'\n',encoding='utf-8')
assets=[p for p in D.iterdir() if p.is_file() and p.name!='SHA256SUMS.txt']
(D/'SHA256SUMS.txt').write_text(''.join(hashlib.sha256(p.read_bytes()).hexdigest()+'  '+p.name+'\n' for p in sorted(assets)),encoding='utf-8')
print('MULTI_BUILD: PASS',V,'OUTPUTS:',', '.join(x.name for x in sorted(assets)))
